import { expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { clewd, tempEnv, writeExtension } from "../test-util";

const api = readFileSync(join(import.meta.dir, "../api.ts"), "utf8");

test("ext init writes clewd.d.ts with the api source and a version header, idempotently", async () => {
  const { env, paths } = tempEnv();
  const first = await clewd(["ext", "init"], env);
  expect(first.code).toBe(0);
  const dts = readFileSync(join(paths.config, "clewd.d.ts"), "utf8");
  expect(dts.split("\n")[0]).toContain("Generated by clewd 0.0.0-dev");
  expect(dts).toEndWith(api);
  expect(existsSync(join(paths.config, "tsconfig.json"))).toBe(true);
  expect(existsSync(paths.extensions)).toBe(true);
  expect((await clewd(["ext", "init"], env)).code).toBe(0);
});

test("any command refreshes a missing or stale clewd.d.ts silently", async () => {
  const { env, paths } = tempEnv();
  await clewd(["version"], env);
  const file = join(paths.config, "clewd.d.ts");
  expect(existsSync(file)).toBe(true);
  await Bun.write(file, "// old");
  const run = await clewd(["version"], env);
  expect(readFileSync(file, "utf8")).toEndWith(api);
  expect(run.stdout).toBe("clewd 0.0.0-dev\n");
});

test("ext new writes a template, prints the path and refuses to overwrite", async () => {
  const { env, paths } = tempEnv();
  const made = await clewd(["ext", "new", "hello"], env);
  const file = join(paths.extensions, "hello.ts");
  expect(made.stdout.trim()).toBe(file);
  const source = readFileSync(file, "utf8");
  expect(source).toContain('import type { Extension } from "../clewd";');
  expect(source).toContain("} satisfies Extension;");
  const again = await clewd(["ext", "new", "hello"], env);
  expect(again.code).toBe(1);
  expect(again.stderr).toContain("already exists");
  expect((await clewd(["ext", "new", "Bad Name"], env)).code).toBe(1);
});

test("end to end: new extension runs, upgrade keeps its own --version flag", async () => {
  const { env } = tempEnv();
  await clewd(["ext", "new", "hello"], env);
  const run = await clewd(["hello", "--name", "Clint"], env);
  expect(run.code).toBe(0);
  expect(run.stdout).toMatch(/^Hello, Clint! You are in \//);
  expect((await clewd(["--version"], env)).stdout).toBe("clewd 0.0.0-dev\n");
  expect((await clewd(["upgrade", "--help"], env)).stdout).toContain("--version");
  expect((await clewd(["ext", "list"], env)).stdout).toContain("commands: hello");
});

test("ext doctor reports a broken extension without crashing, and exits 1", async () => {
  const { env, paths } = tempEnv();
  writeExtension(paths, "broken.ts", `throw new Error("kaboom");`);
  writeExtension(paths, "fine.ts", `export default { name: "fine", commands: [{ name: "version" }] };`);
  const doctor = await clewd(["ext", "doctor"], env);
  expect(doctor.code).toBe(1);
  expect(doctor.stderr).toContain("clewd ext doctor");
  expect(doctor.stdout).toContain("kaboom");
  expect(doctor.stdout).toContain('collision: "version"');
  expect((await clewd(["version"], env)).code).toBe(0);
});

test("no args prints the tagline and root help", async () => {
  const { env } = tempEnv();
  const run = await clewd([], env);
  expect(run.code).toBe(0);
  expect(run.stdout.split("\n")[0]).toBe("There are two kinds of people... those with agent CLIs, and those who grep");
  expect(run.stdout).toContain("Built-in commands");
});
