import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Paths } from "./api";
import { VERSION } from "./version";
// TypeScript resolves this to the api.ts module and sees no default export,
// but Bun's text loader inlines the file's source, also in compiled binaries.
// @ts-expect-error
import apiSource from "./api.ts" with { type: "text" };

const header = `// Generated by clewd ${VERSION}. Do not edit: \`clewd ext init\` refreshes this file.\n`;
const declarations = header + (apiSource as string);

const tsconfig = {
  compilerOptions: {
    target: "ESNext",
    module: "ESNext",
    moduleResolution: "bundler",
    strict: true,
    noEmit: true,
    skipLibCheck: true,
  },
  include: ["*.ts", "extensions/*.ts"],
};

export function declarationsPath(paths: Paths): string {
  return join(paths.config, "clewd.d.ts");
}

export function isStale(paths: Paths): boolean {
  try {
    return readFileSync(declarationsPath(paths), "utf8") !== declarations;
  } catch {
    return true;
  }
}

// Returns the files it wrote. tsconfig.json is the user's once it exists.
export function initFiles(paths: Paths): string[] {
  mkdirSync(paths.extensions, { recursive: true });
  const written = [declarationsPath(paths)];
  writeFileSync(written[0], declarations);
  const tsconfigPath = join(paths.config, "tsconfig.json");
  if (!existsSync(tsconfigPath)) {
    writeFileSync(tsconfigPath, JSON.stringify(tsconfig, null, 2) + "\n");
    written.push(tsconfigPath);
  }
  return written;
}

// Editor support is a convenience: a read-only config dir must not break commands.
export function ensureInit(paths: Paths): void {
  try {
    if (isStale(paths)) initFiles(paths);
  } catch {
    // ignore
  }
}
